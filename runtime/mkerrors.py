import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "data", "vb6", "runtime_errors.json")
d = json.load(open(src, encoding="utf-8"))
errs = {int(k): v for k, v in d["vb"].items()}
errs.update({int(k): v for k, v in d["vba"].items()})      # VBA wins where both exist
# the texts of Error$(n) and Err.Raise n: those of VBA, without 95 (the default text) and 999 (VB6 SP6)
pub = {int(k) for k in d["vba"]} - {95, 999}
def c(s):
    return '"' + s.encode("ascii", "replace").decode().replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'
out = ["/* errors.inc - generated by mkerrors.py from data/vb6/runtime_errors.json; do not edit */",
       "static const struct { int n; const char *s; int pub; } vb_errtab[] = {"]
out += [f"    {{{n}, {c(errs[n])}, {1 if n in pub else 0}}}," for n in sorted(errs)]
out += ["    {0, 0, 0}", "};"]
open(os.path.join(here, "errors.inc"), "w").write("\n".join(out) + "\n")
print(f"errors.inc: {len(errs)} messages")
