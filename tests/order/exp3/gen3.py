# gen3.py - Order3: the evaluation order when the operands are calls WITH arguments (ByVal, ByRef),
# methods of an object, and (for comparison) calls without arguments
import re
RET = {1: 40, 2: 3, 3: 2, 4: 1}
TYPES = {'Integer': 'I', 'Long': 'L', 'Double': 'D', 'Currency': 'C', 'Variant': 'V', 'String': 'S', 'Boolean': 'B', 'Single': 'F'}
KINDS = {'Z': 'no arguments', 'A': 'ByVal argument', 'R': 'ByRef argument', 'M': 'object method'}
SHAPES = ['a + b', 'a - b', 'a * b', 'a < b', 'a And b', 'a & b', 'a + b * c', 'a * b + c', 'a + b + c',
          'a + (b + c)', '(a + b) + (c + d)', 'a * b + c * d', 'a + k + b', 'k + a + b', 'a + v', 'v + a', '-a + b',
          'a + -b', 'a + b + c + d', 'G2(a, b) + c', 'a + G2(b, c)', 'G2(a, b + c)', 'G2(a + b, c)', 'a = b + c',
          'a + b = c', 'a < b And c < d', 'CDbl(a) + b', 'a + CLng(b)', 'CInt(a) + CLng(b)', 'a + b / c']

def val(t, n):
    if t == 'Boolean': return 'True' if n % 2 else 'False'
    if t == 'String': return f'"{RET[n]}"'
    return str(RET[n])

def leaf(t, kind, n):
    s = TYPES[t]
    if kind == 'Z': return f'{s}Z{n}'
    if kind == 'A': return f'{s}A({n})'
    if kind == 'R': return f'{s}R(q{n})'
    return f'o.{s}M({n})'

bas = ['Attribute VB_Name = "Order3"', 'Option Explicit', "' Generated by gen3.py", 'Public mLog As String',
       'Private mF As Integer', 'Private o As CLeaf', 'Private q1 As Long, q2 As Long, q3 As Long, q4 As Long']
cls = ['VERSION 1.0 CLASS', 'BEGIN', '  MultiUse = -1  \'True', 'END', 'Attribute VB_Name = "CLeaf"',
       'Attribute VB_GlobalNameSpace = False', 'Attribute VB_Creatable = True', 'Attribute VB_PredeclaredId = False',
       'Attribute VB_Exposed = False', 'Option Explicit']
for t, s in TYPES.items():
    for n in (1, 2, 3, 4):
        bas += [f'Private Function {s}Z{n}() As {t}', f'    mLog = mLog & "{n}"', f'    {s}Z{n} = {val(t, n)}', 'End Function']
    bas += [f'Private Function {s}A(ByVal n As Integer) As {t}', '    mLog = mLog & n',
            f'    {s}A = Choose(n, {", ".join(val(t, i) for i in (1, 2, 3, 4))})', 'End Function']
    bas += [f'Private Function {s}R(n As Long) As {t}', '    mLog = mLog & n',
            f'    {s}R = Choose(n, {", ".join(val(t, i) for i in (1, 2, 3, 4))})', 'End Function']
    cls += [f'Public Function {s}M(ByVal n As Integer) As {t}', '    mLog = mLog & n',
            f'    {s}M = Choose(n, {", ".join(val(t, i) for i in (1, 2, 3, 4))})', 'End Function']
bas += ['Private Function G2(ByVal x As Variant, ByVal y As Variant) As Variant', '    G2 = x', 'End Function',
        'Private Sub Done(ByVal what As String)',
        '    Print #mF, what; " = "; mLog; IIf(Err.Number, " err" & Err.Number, "")', '    mLog = ""', '    Err.Clear',
        'End Sub']
cases = 0
for t in TYPES:
    for kind in KINDS:
        kval = {'Boolean': 'True', 'String': '"7"'}.get(t, '7')
        bas += [f'Private Sub T_{t}_{kind}()', f'    Dim r As Variant, v As {t}', '    On Error Resume Next', f'    v = {kval}']
        for sh in SHAPES:
            e = sh
            if t == 'String':
                if '-' in e or 'CDbl' in e or 'CLng' in e or 'CInt' in e or '/' in e or 'And' in e: continue
                e = e.replace(' + ', ' & ').replace(' * ', ' & ')
            if t == 'Boolean' and ('-' in e or ' / ' in e): continue
            m = {'k': kval, 'v': 'v', 'a': leaf(t, kind, 1), 'b': leaf(t, kind, 2), 'c': leaf(t, kind, 3), 'd': leaf(t, kind, 4)}
            e = re.sub(r'\b[abcdkv]\b', lambda x: m[x.group(0)], e)
            bas += [f'    r = {e}', f'    Done "{t} {kind} {sh}"']
            cases += 1
        bas.append('End Sub')
# assignments and statements with argument calls
bas += ['Private Sub T_Stmt()', '    Dim x As Long, d As Double, c As Currency, s As String, a(1 To 50) As Long, i As Integer', '    On Error Resume Next']
stmts = [('a(LA(1)) = LA(2)', 'a(LA(1)) = LA(2)'), ('a(LA(1)) = LA(2) + LA(3)', 'a(LA(1)) = LA(2) + LA(3)'),
         ('a(LZ1) = LZ2', 'a(LZ1) = LZ2'), ('a(LZ1) = LZ2 + LZ3', 'a(LZ1) = LZ2 + LZ3'),
         ('a(LA(1)) = DA(2)', 'a(LA(1)) = DA(2)'), ('a(LA(1)) = a(LA(2)) + LA(3)', 'a(LA(1)) = a(LA(2)) + LA(3)'),
         ('x = LA(1) + LA(2)', 'Long target'), ('d = LA(1) + LA(2)', 'Double target: Long +'),
         ('c = CA(1) + CA(2)', 'Currency target'), ('i = IA(1) + IA(2)', 'Integer target'),
         ('If LA(1) = LA(2) Then x = 0', 'If LA(1) = LA(2)'), ('If LA(1) + LA(2) > LA(3) Then x = 0', 'If a + b > c'),
         ('For x = LA(1) To LA(2) Step LA(3): Next', 'For a To b Step c'), ('For x = LZ1 To LZ2 Step LZ3: Next', 'For Z'),
         ('Select Case LA(1): Case LA(2), LA(3): End Select', 'Select Case'),
         ('x = IIf(LA(1) > 0, LA(2), LA(3))', 'IIf'), ('x = Choose(LA(1), LA(2), LA(3))', 'Choose'),
         ('Mid$(s, LA(1), LA(2)) = SA(3)', 'Mid$ stmt'), ('s = Mid$(SA(1), LA(2), LA(3))', 'Mid$ function'),
         ('x = InStr(LA(1), SA(2), SA(3))', 'InStr'), ('s = Left$(SA(1), LA(2)) & SA(3)', 'Left$ & c'),
         ('x = LA(1) + Len(SA(2))', 'a + Len(b)'), ('d = Sqr(DA(1)) + DA(2)', 'Sqr(a) + b'),
         ('o.LM LA(1) + LA(2)', 'method call statement'), ('x = o.LM(LA(1)) + LA(2)', 'method(a) + b'),
         ('Print #mF, LA(1); LA(2); LA(3)', 'Print # items')]
for st, name in stmts:
    bas += [f'    {st}', f'    Done "{name}"']
    cases += 1
bas += ['End Sub', 'Private Function InIDE() As Boolean', '    On Error Resume Next', '    Debug.Print 1 / 0',
        '    InIDE = Err.Number <> 0', '    Err.Clear', 'End Function', 'Sub Main()', '    Set o = New CLeaf',
        '    q1 = 1: q2 = 2: q3 = 3: q4 = 4', '    mF = FreeFile',
        '    Open App.Path & "\\" & App.EXEName & IIf(InIDE(), "-IDE", "") & ".txt" For Output As #mF']
for t in TYPES:
    for kind in KINDS:
        bas.append(f'    T_{t}_{kind}')
bas += ['    T_Stmt', '    Close #mF', '    MsgBox "Done: " & App.EXEName & IIf(InIDE(), "-IDE", "") & ".txt"', 'End Sub']
# CLeaf needs Order3.mLog: a Public variable of a module
cls = [l.replace('mLog = mLog', 'Order3.mLog = Order3.mLog') for l in cls]
open('Order3.bas', 'wb').write(('\r\n'.join(bas) + '\r\n').encode('cp1252'))
open('CLeaf.cls', 'wb').write(('\r\n'.join(cls) + '\r\n').encode('cp1252'))
print(cases, 'cases')
