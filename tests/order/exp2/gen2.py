# gen.py - writes Order2.bas: the evaluation order of VB6 for many types and expression shapes
RET = {1: 40, 2: 3, 3: 2, 4: 1}
TYPES = {   # name -> (VB type, suffix of the leaf functions, operators)
    'Integer': ('Integer', 'I', ['+', '-', '*', '/', '\\', 'Mod', '^', '=', '<', 'And', 'Or', '&']),
    'Long': ('Long', 'L', ['+', '-', '*', '/', '\\', 'Mod', '^', '=', '<', 'And', 'Or', '&']),
    'Byte': ('Byte', 'Y', ['+', '-', '*', '/', '\\', 'Mod', '=', '<', 'And']),
    'Boolean': ('Boolean', 'B', ['+', '=', 'And', 'Or', 'Xor']),
    'Single': ('Single', 'F', ['+', '-', '*', '/', '\\', '^', '=', '<']),
    'Double': ('Double', 'D', ['+', '-', '*', '/', '\\', 'Mod', '^', '=', '<', 'And', '&']),
    'Currency': ('Currency', 'C', ['+', '-', '*', '/', '=', '<']),
    'Date': ('Date', 'T', ['+', '-', '=', '<']),
    'Variant': ('Variant', 'V', ['+', '-', '*', '/', '\\', '^', '=', '<', 'And', '&']),
    'String': ('String', 'S', ['&', '+', '=', '<', 'Like']),
}
SHAPES = [  # with leaves a b c d (calls 1 2 3 4), k a constant, v a variable, + the type's first operator
    'a + b * c', 'a * b + c', 'a + b + c', 'a + (b + c)', '(a + b) + (c + d)', 'a * b + c * d',
    'a + k + b', 'k + a + b', 'a + k', 'k + a', 'v + a', 'a + v', 'v + a + b', 'a + v + b',
    '-a + b', 'a + -b', '(a + b) * c', 'a * (b + c)', 'a + b + c + d', 'a + (b + (c + d))',
    'G2(a, b) + c', 'a + G2(b, c)', 'G2(a, b) + G2(c, d)', 'G3(a, b, c) + d', 'a + G3(b, c, d)',
    'G2(a + b, c)', 'G2(a, b + c)', 'G2(a, b) + c * d', 'a * b + G2(c, d)', 'a = b + c', 'a + b = c',
    'a < b And c < d', 'Abs(a) + b', 'a + Abs(b)', 'CDbl(a) + b', 'a + CLng(b)',
]
MIXED = [('Integer', 'Double'), ('Double', 'Integer'), ('Integer', 'Long'), ('Long', 'Integer'),
         ('Long', 'Single'), ('Integer', 'Variant'), ('Variant', 'Integer'), ('Double', 'Variant'),
         ('String', 'Integer'), ('Integer', 'String'), ('Currency', 'Double'), ('Byte', 'Integer'),
         ('Integer', 'Currency'), ('Date', 'Integer')]

def leaf(t, n):
    return f"{TYPES[t][1]}{n}"

out = ['Attribute VB_Name = "Order2"', 'Option Explicit',
       "' Generated by gen.py: each line is a case and the order in which its calls ran",
       'Private mLog As String', 'Private mF As Integer', 'Private Arr(1 To 50) As Long', 'Private Arr2(1 To 9, 1 To 9) As Long']
for t, (vt, s, ops) in TYPES.items():
    for n in (1, 2, 3, 4):
        if t == 'Boolean':
            val = 'True' if n % 2 else 'False'
        elif t == 'String':
            val = f'"{RET[n]}"'
        elif t == 'Date':
            val = f'CDate({RET[n]})'
        else:
            val = str(RET[n])
        out += [f'Private Function {s}{n}() As {vt}', f'    mLog = mLog & "{n}"', f'    {s}{n} = {val}', 'End Function']
out += ['Private Function G2(ByVal x As Variant, ByVal y As Variant) As Variant', '    G2 = x', 'End Function',
        'Private Function G3(ByVal x As Variant, ByVal y As Variant, ByVal z As Variant) As Variant', '    G3 = x',
        'End Function',
        'Private Function N(ByVal v As Integer) As Long', '    mLog = mLog & v', '    N = v', 'End Function',
        'Private Sub Done(ByVal what As String)', '    Print #mF, what; " = "; mLog; IIf(Err.Number, " err" & Err.Number, "")',
        '    mLog = ""', '    Err.Clear', 'End Sub']
cases = 0
for t, (vt, s, ops) in TYPES.items():
    out += [f'Private Sub T_{t}()', '    Dim r As Variant, v As ' + vt, '    On Error Resume Next']
    kval = {'Boolean': 'True', 'String': '"7"', 'Date': 'CDate(7)'}.get(t, '7')
    out.append(f'    v = {kval}')
    for op in ops:
        e = f"{leaf(t, 1)} {op} {leaf(t, 2)}"
        out += [f'    r = {e}', f'    Done "{t} a {op} b"']
        cases += 1
    for sh in SHAPES:
        e = sh
        if t in ('String',):
            e = e.replace(' + ', ' & ').replace(' * ', ' & ')
        if t == 'Boolean':
            e = e.replace(' * ', ' And ')
        if t == 'Date':
            e = e.replace(' * ', ' + ')
        if t in ('String', 'Date', 'Boolean') and ('Abs(' in e or '-a' in e or '-b' in e):
            continue
        import re
        m = {'k': kval, 'a': leaf(t, 1), 'b': leaf(t, 2), 'c': leaf(t, 3), 'd': leaf(t, 4), 'v': 'v'}
        e = re.sub(r'\b[abcdkv]\b', lambda x: m[x.group(0)], e)
        out += [f'    r = {e}', f'    Done "{t} {sh}"']
        cases += 1
    out.append('End Sub')
out += ['Private Sub T_Mixed()', '    Dim r As Variant', '    On Error Resume Next']
for a, b in MIXED:
    for op in ('+', '&'):
        if op == '+' and 'Date' in (a,) and b == 'Integer':
            pass
        out += [f'    r = {leaf(a, 1)} {op} {leaf(b, 2)}', f'    Done "mixed {a} {op} {b}"']
        out += [f'    r = {leaf(a, 1)} {op} {leaf(b, 2)} {op} {leaf(a, 3)}', f'    Done "mixed {a} {op} {b} {op} {a}"']
        cases += 2
out.append('End Sub')
# typed targets, assignments, calls, statements
out += ['Private Sub T_Other()', '    Dim i As Integer, l As Long, d As Double, s As String, b As Boolean, v As Variant',
        '    Dim o As Collection, x As Long', '    On Error Resume Next']
other = [
    ('i = I1 + I2', 'target Integer: a + b'), ('l = I1 + I2', 'target Long: Integer a + b'),
    ('d = I1 + I2', 'target Double: Integer a + b'), ('d = D1 + D2', 'target Double: Double a + b'),
    ('i = D1 + D2', 'target Integer: Double a + b'), ('s = S1 & S2', 'target String: a & b'),
    ('b = I1 < I2', 'target Boolean: a < b'),
    ('Arr(N(1)) = N(2)', 'Arr(a) = b'), ('Arr(N(1)) = N(2) + N(3)', 'Arr(a) = b + c'),
    ('Arr(N(1) + N(2)) = N(3)', 'Arr(a + b) = c'), ('Arr2(N(1), N(2)) = N(3)', 'Arr2(a, b) = c'),
    ('Arr(N(1)) = Arr(N(2)) + N(3)', 'Arr(a) = Arr(b) + c'), ('x = Arr(N(1)) + Arr(N(2))', 'Arr(a) + Arr(b)'),
    ('Arr(N(1)) = Arr(N(2))', 'Arr(a) = Arr(b)'),
    ('Set o = New Collection: o.Add N(1), CStr(N(2)): o.Add N(3)', 'o.Add a, CStr(b)'),
    ('x = o(N(1)) + N(2)', 'o(a) + b'), ('x = N(1) + o.Count', 'a + o.Count'),
    ('Mid$(s, N(1), N(2)) = CStr(N(3))', 'Mid$(s, a, b) = c'),
    ('s = String$(5, "x"): Mid$(s, N(1), N(2)) = CStr(N(3))', 'Mid$ stmt 2'),
    ('If N(1) = N(2) Then x = 0', 'If a = b'), ('If N(1) + N(2) > N(3) Then x = 0', 'If a + b > c'),
    ('Do While N(1) > N(2): Loop', 'Do While a > b'),
    ('For x = N(1) To N(2) Step N(3): Next', 'For x = a To b Step c'),
    ('Select Case N(1): Case N(2), N(3): End Select', 'Select Case a / Case b, c'),
    ('v = IIf(N(1) > 0, N(2), N(3))', 'IIf(a, b, c)'), ('v = Choose(N(1), N(2), N(3))', 'Choose(a, b, c)'),
    ('v = Switch(N(1) = 1, N(2), N(3) = 3, N(4))', 'Switch'),
    ('x = N(1) + N(2): x = N(3)', 'two statements'),
    ('x = N(1) Mod N(2) + N(3) \\ N(4)', 'a Mod b + c \\ d'),
    ('d = N(1) / N(2) + N(3)', 'Long a / b + c'), ('d = N(1) ^ N(2) + N(3)', 'Long a ^ b + c'),
    ('v = N(1) & N(2) + N(3)', 'a & b + c'), ('v = N(1) + N(2) & N(3)', 'a + b & c'),
    ('b = N(1) = N(2) Or N(3) = N(4)', 'a = b Or c = d'), ('b = Not N(1) = N(2)', 'Not a = b'),
    ('x = -N(1) - -N(2)', '-a - -b'), ('x = N(1) - N(2) - N(3)', 'a - b - c'),
    ('d = N(1) / N(2) / N(3)', 'a / b / c'), ('d = N(1) ^ N(2) ^ N(3)', 'a ^ b ^ c'),
]
for st, name in other:
    out += [f'    {st}', f'    Done "{name}"']
    cases += 1
out += ['End Sub',
        'Private Function InIDE() As Boolean', '    On Error Resume Next', '    Debug.Print 1 / 0',
        '    InIDE = Err.Number <> 0', '    Err.Clear', 'End Function',
        'Sub Main()', '    mF = FreeFile',
        '    Open App.Path & "\\" & App.EXEName & IIf(InIDE(), "-IDE", "") & ".txt" For Output As #mF']
for t in TYPES:
    out.append(f'    T_{t}')
out += ['    T_Mixed', '    T_Other', '    Close #mF', '    MsgBox "Done: " & App.EXEName & IIf(InIDE(), "-IDE", "") & ".txt"', 'End Sub']
open('Order2.bas', 'wb').write(('\r\n'.join(out) + '\r\n').encode('cp1252'))
print(cases, 'cases', len(out), 'lines')
